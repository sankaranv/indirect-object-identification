# indirect-object-identification/experiments/fig6_circuit_validation.py
"""Figure 6: Circuit faithfulness and completeness via mean ablation.

Uses the 1000-example reference dataset (data/ioi/gpt2.csv) for low-variance
estimates. ABC means are generated by replacing both IO and S names with random
names, giving properly neutral baselines for mean ablation.
"""
import os, sys, json, re, torch
import pandas as pd
import matplotlib.pyplot as plt
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
torch.set_grad_enabled(False)

from utils import load_model
from metrics import logit_diff
from circuit import CIRCUIT, SEQ_POS_TO_KEEP, compute_means, run_with_mean_ablation

CSV_PATH = os.path.join(os.path.dirname(__file__), "..", "data", "ioi", "gpt2.csv")

_ABC_NAMES = [
    "Tyler", "Connor", "Derek", "Spencer", "Grant", "Chad",
    "Blake", "Seth", "Brett", "Wade", "Todd", "Reed",
    "Kirk", "Brent", "Troy", "Cody",
]


def _make_abc_texts(df, tok):
    """Replace both IO and S names with distinct random names per example."""
    texts = []
    for i, (_, row) in enumerate(df.iterrows()):
        io_name = tok.decode([row["correct_idx"]]).strip()
        s_name  = tok.decode([row["incorrect_idx"]]).strip()
        r1 = _ABC_NAMES[(i * 2)     % len(_ABC_NAMES)]
        r2 = _ABC_NAMES[(i * 2 + 1) % len(_ABC_NAMES)]
        text = re.sub(r"\b" + re.escape(io_name) + r"\b", r1, row["clean"])
        text = re.sub(r"\b" + re.escape(s_name)  + r"\b", r2, text)
        texts.append(text)
    return texts


def _build_word_idx(clean_toks, s_ids, seq_len):
    """Build end / S2 / S+1 position tensors from tokenised clean prompts."""
    N = clean_toks.shape[0]
    end_pos    = torch.full((N,), seq_len - 1, dtype=torch.long)
    S2_pos     = torch.zeros(N, dtype=torch.long)
    Splus1_pos = torch.zeros(N, dtype=torch.long)
    ep = seq_len - 1
    for i in range(N):
        sid  = s_ids[i].item()
        hits = (clean_toks[i, :ep] == sid).nonzero(as_tuple=True)[0]
        if len(hits) >= 2:
            S2_pos[i]     = hits[-1]
            Splus1_pos[i] = hits[0] + 1
        elif len(hits) == 1:
            S2_pos[i]     = hits[0]
            Splus1_pos[i] = hits[0] + 1
        else:
            S2_pos[i] = ep - 1; Splus1_pos[i] = ep - 2
    return {"end": end_pos, "S2": S2_pos, "S+1": Splus1_pos}


def run():
    model = load_model()
    tok   = model.tokenizer  # left-padded by default

    df     = pd.read_csv(CSV_PATH)
    N      = len(df)
    io_ids = torch.tensor(df["correct_idx"].tolist())
    s_ids  = torch.tensor(df["incorrect_idx"].tolist())

    clean_enc  = tok(df["clean"].tolist(), return_tensors="pt", padding=True)
    abc_enc    = tok(_make_abc_texts(df, tok), return_tensors="pt", padding=True)
    clean_toks = clean_enc.input_ids
    abc_toks   = abc_enc.input_ids
    seq_len    = clean_toks.shape[1]

    word_idx = _build_word_idx(clean_toks, s_ids, seq_len)
    end_pos  = word_idx["end"]

    def ld(logits):
        return logit_diff(
            logits[torch.arange(N), end_pos], io_ids, s_ids
        ).mean().item()

    print(f"Computing ABC means ({N} examples)…")
    means = compute_means(model, abc_toks, [[i] for i in range(N)])

    with model.trace({"input_ids": clean_toks}):
        full_logits = model.lm_head.output.save()
    full_ld = ld(full_logits.cpu())

    faithful_logits = run_with_mean_ablation(
        model, clean_toks, means, CIRCUIT, SEQ_POS_TO_KEEP, word_idx
    )
    faithful_ld = ld(faithful_logits.cpu())

    complete_logits = run_with_mean_ablation(
        model, clean_toks, means,
        {k: [] for k in CIRCUIT}, SEQ_POS_TO_KEEP, word_idx,
    )
    complete_ld = ld(complete_logits.cpu())

    faith_ratio = faithful_ld / (full_ld + 1e-8)
    compl_ratio = complete_ld / (full_ld + 1e-8)

    print(f"\n[Figure 6]")
    print(f"  Full:              {full_ld:.4f}  (paper 3.56)")
    print(f"  Circuit only:      {faithful_ld:.4f}  (paper 3.10)")
    print(f"  Circuit ablated:   {complete_ld:.4f}  (expected ~0)")
    print(f"  Faithfulness:      {faith_ratio:.1%}  (paper 87%)")
    print(f"  Completeness rem.: {compl_ratio:.1%}  (target <5%)")

    fig, ax = plt.subplots(figsize=(6, 4))
    bars = ax.bar(
        ["Full", "Circuit only\n(faithful)", "Circuit ablated\n(complete)"],
        [full_ld, faithful_ld, complete_ld],
        color=["#4C72B0", "#55A868", "#C44E52"],
    )
    ax.axhline(0, color="k", lw=0.8)
    ax.set_ylabel("Logit diff (IO − S)")
    ax.set_title("Circuit Faithfulness & Completeness (Figure 6)")
    for b, v in zip(bars, [full_ld, faithful_ld, complete_ld]):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.05, f"{v:.2f}", ha="center")
    plt.tight_layout()
    os.makedirs("plots/circuit", exist_ok=True)
    plt.savefig("plots/circuit/fig6.png", dpi=150); plt.close()

    os.makedirs("results/circuit", exist_ok=True)
    with open("results/circuit/faithfulness.json", "w") as f:
        json.dump({"full": full_ld, "faithful": faithful_ld, "complete": complete_ld,
                   "faithfulness": faith_ratio, "completeness_remaining": compl_ratio}, f, indent=2)

    assert faith_ratio > 0.80, f"Faithfulness {faith_ratio:.1%} < 80%"
    assert abs(compl_ratio) < 0.10, f"Completeness remainder {compl_ratio:.1%} outside ±10%"
    print("PASS")


if __name__ == "__main__":
    run()
